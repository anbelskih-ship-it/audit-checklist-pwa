import type { Audit, ChecklistStructure } from '../types'
import { calcMetrics } from '../utils/metrics'
import { getSectionEvalItems, getSheetEvalItems } from '../utils/checklist-items'

/**
 * Универсальный промпт для любой LLM-модели (Gemini, Claude, GPT, Llama).
 * Собирает данные аудита и формирует бриф для генерации
 * дипломатичного, клиентоориентированного резюме зон роста.
 */
export function buildAuditPrompt(audit: Audit, structure: ChecklistStructure): string {
  const allEvalItems = structure.sheets.flatMap(getSheetEvalItems)
  const { filled, total, yesCount } = calcMetrics(allEvalItems, audit.answers)
  const overallScore = filled > 0 ? Math.round((yesCount / filled) * 100) : 0

  const sheetBlocks: string[] = []
  for (const sheet of structure.sheets) {
    const evalItems = getSheetEvalItems(sheet)
    const m = calcMetrics(evalItems, audit.answers)
    const sheetScore = m.filled > 0 ? Math.round((m.yesCount / m.filled) * 100) : 0

    const issues: string[] = []
    for (const section of sheet.sections) {
      for (const item of getSectionEvalItems(section)) {
        const a = audit.answers[item.id]
        if (a?.value === 0) {
          let line = `- ${item.text}`
          if (a.comment) line += `\n  Комментарий консультанта: ${a.comment}`
          issues.push(line)
        }
      }
    }

    if (issues.length > 0) {
      sheetBlocks.push(
        `## ${sheet.name} — результат ${sheetScore}%\n${issues.join('\n')}`
      )
    }
  }

  const prompt = `Ты — старший консультант по операционной эффективности автомобильного дилерского центра. Тебе дан результат аудита. Сформируй выжимку.

ФОРМАТ ОТВЕТА (строго):

1. КЛЮЧЕВЫЕ ЗОНЫ РОСТА
- 5-7 буллитов максимум
- каждый буллит = 1 управленческая тема
- можно объединять несколько листов в один буллит, если смысл общий
- формат буллита:
"- {краткий заголовок}: {1-2 предложения, где кратко описано, в чём зона роста и где она проявляется}"

2. СВЯЗКИ МЕЖДУ БЛОКАМИ
- 3-5 буллитов максимум
- показать, как одна зона роста влияет сразу на несколько процессов
- формат буллита:
"- {связка}: {какие блоки связаны и какой общий эффект это даёт бизнесу}"

3. ПРИОРИТЕТНЫЕ ДЕЙСТВИЯ
- 5 буллитов максимум
- каждое действие должно быть управленческим, конкретным и укрупнённым
- не писать отдельное действие на каждый лист
- формат буллита:
"- {действие}: {что сделать в первую очередь и какой эффект это даст}"

4. ИТОГ
- 2 коротких предложения
- нейтральный деловой тон
- без жёстких оценок дилера
- сфокусироваться на потенциале улучшения и ближайшем фокусе руководителя

ЗАПРЕТЫ:
- НЕ пиши приветствие, преамбулу, обращение ("Уважаемые", "По итогам" и т.д.)
- НЕ используй слова и формулировки, из-за которых дилеру может быть неловко:
"провал", "критично", "катастрофа", "ошибка", "нарушение", "несоответствие", "слабое звено", "не умеют"
- Вместо этого используй мягкий консалтинговый язык:
"зона роста", "есть потенциал усиления", "требует формализации", "полезно закрепить", "нужна регулярность", "целесообразно вывести в стандарт"
- НЕ пересказывай подряд все замечания из каждого листа
- НЕ дублируй одну и ту же мысль в нескольких буллитах
- НЕ делай длинные перечисления через запятую на полэкрана
- НЕ давай более одной рекомендации на одну и ту же тему
- НЕ используй markdown-заголовки \`#\`, \`##\`, \`###\`
- Используй только короткие обычные заголовки строк и буллиты с \`-\`
- Объём: не более 220 слов
- Язык: русский

ДАННЫЕ АУДИТА:
Тип: ${audit.type}
ДЦ: ${audit.dealership}, ${audit.city}
Дата: ${new Date(audit.updated).toLocaleDateString('ru')}
Заполнено: ${filled}/${total}
Общий результат: ${overallScore}%

ПРАВИЛА ИНТЕРПРЕТАЦИИ:
- Смотри на замечания не по листам, а по смысловым кластерам
- Разрешено объединять связанные блоки, например:
  контроль + CRM + показатели
  подбор + обучение + мотивация
  выкуп + трейд-ин + платформа
  диагностика + предпродажная подготовка + сроки публикации
  маркетинг + NPS + клиентский путь
- Если в комментариях несколько близких замечаний, объединяй их в одну мысль
- Сначала показывай управленческий смысл, потом примеры из блоков

ЗОНЫ РОСТА:
${sheetBlocks.length > 0 ? sheetBlocks.join('\n\n') : 'Зон роста не выявлено.'}`

  return prompt
}
